#pragma once

#include <Arduino.h>
#include <stdint.h>

// ============================================================
// ALARM CONFIGURATION
// ============================================================

namespace AlarmConfig
{
    static constexpr uint8_t MAX_ALARMS = 8;
}

// ============================================================
// ALARM TIME
// ============================================================

struct AlarmTime
{
    uint8_t hour   = 0;
    uint8_t minute = 0;
    uint8_t second = 0;
};

// ============================================================
// ALARM
// ============================================================

struct Alarm
{
    // Версия JSON/структуры.
    uint16_t schemaVersion = 1;

    // UUID v4.
    // При создании может быть пустым.
    String id;

    // Название будильника.
    String name;

    // Включен ли будильник.
    bool enabled = false;

    // Время срабатывания.
    AlarmTime time;

    // ========================================================
    // REPEAT MASK
    // ========================================================
    //
    // bit 0 = Monday
    // bit 1 = Tuesday
    // bit 2 = Wednesday
    // bit 3 = Thursday
    // bit 4 = Friday
    // bit 5 = Saturday
    // bit 6 = Sunday
    //
    // 0   = одноразовый
    // 31  = Пн-Пт
    // 127 = каждый день
    //
    uint8_t repeatMask = 0;

    // ========================================================
    // EFFECTS
    // ========================================================

    // Эффект матрицы.
    // "" = не использовать.
    String matrixEffect;

    // Эффект COB-подсветки.
    // "" = не использовать.
    String cobEffect;

    // Звуковой эффект.
    // "" = не использовать.
    String audioEffect;
};