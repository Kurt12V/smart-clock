#pragma once

#include <Arduino.h>
#include <time.h>

// ============================================================
// ALARM LIMITS
// ============================================================

namespace AlarmLimits
{
    // Максимальное количество будильников
    constexpr uint8_t MAX_ALARMS = 16;

    // Максимальное количество фаз одного будильника
    constexpr uint8_t MAX_PHASES = 16;

    // Максимальные размеры строк
    constexpr size_t MAX_ID_LENGTH = 40;
    constexpr size_t MAX_NAME_LENGTH = 64;
    constexpr size_t MAX_EFFECT_ID_LENGTH = 32;
    constexpr size_t MAX_CONDITION_LENGTH = 32;
}


// ============================================================
// ALARM TIME
// ============================================================

struct AlarmTime
{
    uint8_t hour = 0;
    uint8_t minute = 0;
    uint8_t second = 0;
};


// ============================================================
// ALARM EFFECT
// ============================================================
//
// Универсальный эффект для:
// - LED Matrix
// - Audio
// - COB
//
// Пример:
// Matrix:
// start = 0
// end = 30
//
// Audio:
// start = 0
// end = 80
//
// COB:
// start = 0
// end = 100
//

struct AlarmEffect
{
    // Включен ли эффект
    bool enabled = false;

    // ID эффекта
    //
    // Например:
    // "fade"
    // "pulse"
    // "blink"
    // "static"
    // "melody"
    char effectId[AlarmLimits::MAX_EFFECT_ID_LENGTH] = {0};

    // Начальное значение
    int16_t start = 0;

    // Конечное значение
    int16_t end = 0;

    // Скорость эффекта
    //
    // Например:
    // 500  = 500 ms
    // 1000 = 1 секунда
    uint32_t speedMs = 0;

    // Продолжительность эффекта
    uint32_t durationMs = 0;

    // Зациклить эффект
    bool loop = false;

    // Максимальное время работы.
    //
    // 0 = без ограничения.
    //
    // Например:
    // COB может работать максимум 5 минут.
    uint32_t maxDurationMs = 0;
};


// ============================================================
// ALARM PHASE
// ============================================================
//
// Одна фаза сценария будильника.
//
// Например:
//
// Phase 1:
// 0 -> 10 минут
//
// Phase 2:
// 0 -> 30 секунд
//
// Phase 3:
// 30 -> 60 секунд
//
// Phase 4:
// 60 секунд -> dismiss
//

struct AlarmPhase
{
    // --------------------------------------------------------
    // START OFFSET
    // --------------------------------------------------------
    //
    // Смещение относительно момента срабатывания T0.
    //
    // 0       = сразу
    // 30000   = через 30 секунд
    // 60000   = через 1 минуту
    //

    int64_t startOffsetMs = 0;


    // --------------------------------------------------------
    // PHASE DURATION
    // --------------------------------------------------------
    //
    // Длительность всей фазы.
    //
    // 0 = без ограничения.
    //

    uint32_t durationMs = 0;


    // --------------------------------------------------------
    // CONDITION
    // --------------------------------------------------------
    //
    // Возможные значения:
    //
    // "always"
    // "if_not_dismissed"
    // "if_no_motion"
    //
    // И т.д.
    //

    char condition[AlarmLimits::MAX_CONDITION_LENGTH] = "always";


    // --------------------------------------------------------
    // MATRIX
    // --------------------------------------------------------

    AlarmEffect matrix;


    // --------------------------------------------------------
    // AUDIO
    // --------------------------------------------------------

    AlarmEffect audio;


    // --------------------------------------------------------
    // COB
    // --------------------------------------------------------

    AlarmEffect cob;
};


// ============================================================
// FULL ALARM DATA
// ============================================================
//
// Полное описание будильника.
//
// Эта структура соответствует данным в alarms.json.
//
// В режиме ожидания НЕ обязательно держать ее в RAM.
//
// Она загружается с SD, когда наступает время срабатывания.
//

struct AlarmData
{
    // --------------------------------------------------------
    // ID
    // --------------------------------------------------------
    //
    // Например:
    // "alarm_morning"
    //

    char id[AlarmLimits::MAX_ID_LENGTH] = {0};


    // --------------------------------------------------------
    // NAME
    // --------------------------------------------------------
    //
    // Например:
    // "Утро"
    //

    char name[AlarmLimits::MAX_NAME_LENGTH] = {0};


    // --------------------------------------------------------
    // ENABLED
    // --------------------------------------------------------

    bool enabled = false;


    // --------------------------------------------------------
    // TIME
    // --------------------------------------------------------

    AlarmTime time;


    // --------------------------------------------------------
    // REPEAT MASK
    // --------------------------------------------------------
    //
    // Биты:
    //
    // 1   = Понедельник
    // 2   = Вторник
    // 4   = Среда
    // 8   = Четверг
    // 16  = Пятница
    // 32  = Суббота
    // 64  = Воскресенье
    //
    // Примеры:
    //
    // 0   = одноразовый
    // 31  = Пн-Пт
    // 96  = Сб-Вс
    // 127 = каждый день
    //

    uint8_t repeatMask = 0;


    // --------------------------------------------------------
    // PHASES
    // --------------------------------------------------------

    uint8_t phaseCount = 0;

    AlarmPhase phases[AlarmLimits::MAX_PHASES];
};


// ============================================================
// ALARM SCHEDULE DATA
// ============================================================
//
// Минимальные данные, которые постоянно находятся в RAM.
//
// Здесь НЕТ phases.
// Здесь НЕТ matrix.
// Здесь НЕТ audio.
// Здесь НЕТ cob.
//
// Пока будильник ожидает:
// RAM хранит только:
//
// ID
// enabled
// время
// repeatMask
// nextTrigger
//
// Когда nextTrigger наступает:
//
// ID -> SD -> AlarmData
//

struct AlarmScheduleData
{
    // --------------------------------------------------------
    // ID
    // --------------------------------------------------------
    //
    // По этому ID потом загружается полный AlarmData с SD.
    //

    char id[AlarmLimits::MAX_ID_LENGTH] = {0};


    // --------------------------------------------------------
    // ENABLED
    // --------------------------------------------------------

    bool enabled = false;


    // --------------------------------------------------------
    // TIME
    // --------------------------------------------------------

    uint8_t hour = 0;
    uint8_t minute = 0;
    uint8_t second = 0;


    // --------------------------------------------------------
    // REPEAT MASK
    // --------------------------------------------------------

    uint8_t repeatMask = 0;


    // --------------------------------------------------------
    // NEXT TRIGGER
    // --------------------------------------------------------
    //
    // Абсолютное время следующего срабатывания.
    //
    // Это runtime-поле.
    //
    // В alarms.json его хранить НЕ нужно.
    //

    time_t nextTrigger = 0;
};


// ============================================================
// ACTIVE ALARM DATA
// ============================================================
//
// Используется только после срабатывания.
//
// В этот момент полный AlarmData загружается с SD.
//

struct ActiveAlarmData
{
    // --------------------------------------------------------
    // ACTIVE
    // --------------------------------------------------------

    bool active = false;


    // --------------------------------------------------------
    // ID
    // --------------------------------------------------------

    char id[AlarmLimits::MAX_ID_LENGTH] = {0};


    // --------------------------------------------------------
    // STARTED AT
    // --------------------------------------------------------
    //
    // millis() в момент запуска будильника.
    //

    uint32_t startedAtMs = 0;


    // --------------------------------------------------------
    // CURRENT PHASE
    // --------------------------------------------------------
    //
    // Индекс текущей фазы.
    //

    uint8_t currentPhase = 0;


    // --------------------------------------------------------
    // FULL ALARM DATA
    // --------------------------------------------------------
    //
    // Полностью загруженные данные с SD.
    //

    AlarmData data;
};


// ============================================================
// ALARM DATABASE
// ============================================================
//
// Если нужно загрузить весь alarms.json целиком.
//
// Используется для редактирования/сохранения базы.
// Для обычного ожидания будильников эта структура не нужна.
//

struct AlarmDatabase
{
    // Версия JSON-схемы
    uint8_t schemaVersion = 1;

    // Количество будильников
    uint8_t alarmCount = 0;

    // Все будильники
    AlarmData alarms[AlarmLimits::MAX_ALARMS];
};