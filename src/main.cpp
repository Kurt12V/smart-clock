
#include <Arduino.h>
#include "./core/App.h"

// ============================================================
// GLOBAL APPLICATION
// ============================================================

App app;

// ============================================================
// SETUP
// ============================================================

void setup() {

    Serial0.begin(115200);

    delay(500);

    Serial0.println();
    Serial0.println("================================");
    Serial0.println("       SMARTCLOCK START");
    Serial0.println("================================");

    app.begin();

    Serial0.println("[MAIN] App initialized");
}

// ============================================================
// LOOP
// ============================================================

void loop() {

    app.update();

}
 