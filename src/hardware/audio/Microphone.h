#pragma once

#include <Arduino.h>

class I2SManager;

// ============================================================
// Microphone
// INMP441 microphone abstraction
// ============================================================

class Microphone
{
public:

    // --------------------------------------------------------
    // CONFIG
    // --------------------------------------------------------

    static constexpr uint32_t DEFAULT_SAMPLE_RATE = 16000;

    static constexpr size_t AUDIO_SAMPLES = 512;

    // --------------------------------------------------------
    // CONSTRUCTOR
    // --------------------------------------------------------

    explicit Microphone(I2SManager& i2sManager);

    // --------------------------------------------------------
    // LIFECYCLE
    // --------------------------------------------------------

    bool begin();
    void end();

    // --------------------------------------------------------
    // LISTENING
    // --------------------------------------------------------

    bool startListening();
    void stopListening();

    bool updateAudio();

    // --------------------------------------------------------
    // AUDIO DATA
    // --------------------------------------------------------

    bool hasNewAudio() const;

    uint32_t getAudioChunkId() const;

    size_t getAudioChunk(
        const int16_t*& samples
    ) const;

    size_t getAudioChunkSize() const;

    // --------------------------------------------------------
    // AUDIO ANALYSIS
    // --------------------------------------------------------

    float getRMS() const;
    float getLevel() const;
    int16_t getPeak() const;

    // --------------------------------------------------------
    // STATE
    // --------------------------------------------------------

    bool isInitialized() const;
    bool isListening() const;

    // --------------------------------------------------------
    // ENABLE
    // --------------------------------------------------------

    bool isEnabled() const;
    void setEnabled(bool enabled);

    // --------------------------------------------------------
    // INFO
    // --------------------------------------------------------

    const char* getName() const;

private:

    // --------------------------------------------------------
    // I2S
    // --------------------------------------------------------

    I2SManager& i2sManager;

    // --------------------------------------------------------
    // STATE
    // --------------------------------------------------------

    bool initialized;
    bool listening;
    bool enabled;

    // --------------------------------------------------------
    // AUDIO
    // --------------------------------------------------------

    uint32_t audioChunkId;

    size_t audioChunkSize;

    // --------------------------------------------------------
    // ANALYSIS
    // --------------------------------------------------------

    float rms;
    float level;
    int16_t peak;

    // --------------------------------------------------------
    // BUFFER
    // --------------------------------------------------------

    int16_t audioBuffer[AUDIO_SAMPLES];
};
