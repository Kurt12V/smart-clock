#include "Display.h"
#include "Pins.h"

#include <Arduino.h>
#include <SPI.h>


// ============================================================
// Массивы GPIO
// ============================================================

static const int8_t TFT_CS[Display::COUNT] =
{
    PIN_TFT_CS1,
    PIN_TFT_CS2,
    PIN_TFT_CS3,
    PIN_TFT_CS4
};


static const int8_t TFT_RST[Display::COUNT] =
{
    PIN_TFT_RST1,
    PIN_TFT_RST2,
    PIN_TFT_RST3,
    PIN_TFT_RST4
};


// ============================================================
// ST7789_172x320
// ============================================================

ST7789_172x320::ST7789_172x320(
    int8_t cs,
    int8_t dc,
    int8_t rst,
    int8_t mosi,
    int8_t sclk
)
    : Adafruit_ST7789(
        cs,
        dc,
        mosi,
        sclk,
        rst
    )
{
}


// ============================================================
// Инициализация одного дисплея
// ============================================================

void ST7789_172x320::begin172x320()
{
    /*
     * Инициализация физической матрицы
     */
    init(
        172,
        320,
        SPI_MODE0
    );


    /*
     * Реальный ST7789 часто имеет
     * встроенную область 240x320.
     *
     * Наш видимый экран начинается
     * с X = 34.
     */
    setColRowStart(
        34,
        0
    );


    /*
     * 8 MHz — безопасная скорость
     * для четырёх дисплеев на одной
     * SPI-шине.
     */
    setSPISpeed(
        8000000UL
    );


    /*
     * Ориентация.
     */
    setRotation(0);


    /*
     * Для используемого модуля
     * изображение требует инверсии.
     */
    invertDisplay(true);
}


// ============================================================
// Выбор дисплея
// ============================================================

void ST7789_172x320::select()
{
    /*
     * CS LOW = дисплей выбран.
     *
     * В нормальном режиме Adafruit_ST7789
     * сам управляет CS, поэтому здесь
     * оставляем функцию как дополнительный
     * интерфейс.
     */
}


// ============================================================
// Снятие выбора
// ============================================================

void ST7789_172x320::deselect()
{
    /*
     * Управление CS производится
     * через GPIO, соответствующий
     * этому объекту.
     *
     * Adafruit_ST7789 хранит CS внутри
     * базового класса, поэтому фактическое
     * управление выполняется Display.
     */
}


// ============================================================
// Display constructor
// ============================================================

Display::Display()
    :
      _display
      {
          ST7789_172x320(
              PIN_TFT_CS1,
              PIN_TFT_DC,
              PIN_TFT_RST1,
              PIN_TFT_MOSI,
              PIN_TFT_SCLK
          ),

          ST7789_172x320(
              PIN_TFT_CS2,
              PIN_TFT_DC,
              PIN_TFT_RST2,
              PIN_TFT_MOSI,
              PIN_TFT_SCLK
          ),

          ST7789_172x320(
              PIN_TFT_CS3,
              PIN_TFT_DC,
              PIN_TFT_RST3,
              PIN_TFT_MOSI,
              PIN_TFT_SCLK
          ),

          ST7789_172x320(
              PIN_TFT_CS4,
              PIN_TFT_DC,
              PIN_TFT_RST4,
              PIN_TFT_MOSI,
              PIN_TFT_SCLK
          )
      },

      _initialized(false),
      _backlight(false)
{
}


// ============================================================
// Настройка GPIO
// ============================================================

void Display::setupPins()
{
    /*
     * --------------------------------------------------------
     * Backlight
     * --------------------------------------------------------
     */

    pinMode(
        PIN_TFT_BL,
        OUTPUT
    );

    digitalWrite(
        PIN_TFT_BL,
        LOW
    );


    /*
     * --------------------------------------------------------
     * DC
     * --------------------------------------------------------
     */

    pinMode(
        PIN_TFT_DC,
        OUTPUT
    );

    digitalWrite(
        PIN_TFT_DC,
        LOW
    );


    /*
     * --------------------------------------------------------
     * CS
     * --------------------------------------------------------
     */

    for (uint8_t i = 0; i < COUNT; i++)
    {
        pinMode(
            TFT_CS[i],
            OUTPUT
        );

        /*
         * Все дисплеи выключены.
         */
        digitalWrite(
            TFT_CS[i],
            HIGH
        );
    }


    /*
     * --------------------------------------------------------
     * RST
     * --------------------------------------------------------
     */

    for (uint8_t i = 0; i < COUNT; i++)
    {
        pinMode(
            TFT_RST[i],
            OUTPUT
        );

        /*
         * Не держим дисплей в reset.
         */
        digitalWrite(
            TFT_RST[i],
            HIGH
        );
    }
}


// ============================================================
// Выключить все дисплеи
// ============================================================

void Display::disableAllDisplays()
{
    for (uint8_t i = 0; i < COUNT; i++)
    {
        digitalWrite(
            TFT_CS[i],
            HIGH
        );
    }
}


// ============================================================
// Инициализация одного дисплея
// ============================================================

bool Display::initializeDisplay(
    uint8_t index
)
{
    if (index >= COUNT)
    {
        return false;
    }


    /*
     * Очень важно:
     *
     * перед инициализацией конкретного
     * дисплея все остальные CS должны
     * быть HIGH.
     */

    disableAllDisplays();


    /*
     * Выбираем только этот дисплей.
     */

    digitalWrite(
        TFT_CS[index],
        LOW
    );


    /*
     * Инициализация ST7789.
     */

    _display[index].begin172x320();


    /*
     * После init снова снимаем CS.
     */

    digitalWrite(
        TFT_CS[index],
        HIGH
    );


    return true;
}


// ============================================================
// begin()
// ============================================================

bool Display::begin()
{
    if (_initialized)
    {
        return true;
    }


    /*
     * --------------------------------------------------------
     * GPIO
     * --------------------------------------------------------
     */

    setupPins();


    /*
     * --------------------------------------------------------
     * SPI
     *
     * ESP32-S3:
     *
     * SCLK = 12
     * MISO = -1
     * MOSI = 11
     * SS   = -1
     *
     * CS управляется самими дисплеями.
     * --------------------------------------------------------
     */

    SPI.begin(
        PIN_TFT_SCLK,
        -1,
        PIN_TFT_MOSI,
        -1
    );


    /*
     * --------------------------------------------------------
     * Начальное состояние
     * --------------------------------------------------------
     */

    disableAllDisplays();


    /*
     * --------------------------------------------------------
     * Инициализация всех 4 дисплеев
     * --------------------------------------------------------
     */

    for (uint8_t i = 0; i < COUNT; i++)
    {
        if (!initializeDisplay(i))
        {
            disableAllDisplays();

            setBacklight(false);

            return false;
        }
    }


    /*
     * --------------------------------------------------------
     * Очистка каждого дисплея
     * --------------------------------------------------------
     */

    for (uint8_t i = 0; i < COUNT; i++)
    {
        select(i);

        _display[i].fillScreen(
            ST77XX_BLACK
        );

        digitalWrite(
            TFT_CS[i],
            HIGH
        );
    }


    /*
     * --------------------------------------------------------
     * Backlight
     * --------------------------------------------------------
     */

    setBacklight(true);


    _initialized = true;

    return true;
}


// ============================================================
// Проверка инициализации
// ============================================================

bool Display::isInitialized() const
{
    return _initialized;
}


// ============================================================
// Получить дисплей
// ============================================================

ST7789_172x320& Display::get(
    uint8_t index
)
{
    /*
     * Защита от выхода за массив.
     */
    if (index >= COUNT)
    {
        index = 0;
    }

    return _display[index];
}


// ============================================================
// Получить указатель
// ============================================================

ST7789_172x320* Display::getPtr(
    uint8_t index
)
{
    if (index >= COUNT)
    {
        return nullptr;
    }

    return &_display[index];
}


// ============================================================
// Выбрать дисплей
// ============================================================

void Display::select(
    uint8_t index
)
{
    if (index >= COUNT)
    {
        return;
    }


    /*
     * Сначала выключаем все.
     */
    disableAllDisplays();


    /*
     * Затем выбираем только один.
     */
    digitalWrite(
        TFT_CS[index],
        LOW
    );
}


// ============================================================
// Снять выбор со всех
// ============================================================

void Display::deselectAll()
{
    disableAllDisplays();
}


// ============================================================
// Очистить все дисплеи
// ============================================================

void Display::clear(
    uint16_t color
)
{
    for (uint8_t i = 0; i < COUNT; i++)
    {
        select(i);

        _display[i].fillScreen(
            color
        );
    }

    deselectAll();
}


// ============================================================
// Очистить один дисплей
// ============================================================

void Display::clear(
    uint8_t index,
    uint16_t color
)
{
    if (index >= COUNT)
    {
        return;
    }

    select(index);

    _display[index].fillScreen(
        color
    );

    digitalWrite(
        TFT_CS[index],
        HIGH
    );
}


// ============================================================
// Backlight
// ============================================================

void Display::setBacklight(
    bool state
)
{
    digitalWrite(
        PIN_TFT_BL,
        state ? HIGH : LOW
    );

    _backlight = state;
}


// ============================================================
// Состояние Backlight
// ============================================================

bool Display::backlightState() const
{
    return _backlight;
}


// ============================================================
// SPI transaction BEGIN
// ============================================================

void Display::beginTransaction()
{
    SPI.beginTransaction(
        SPISettings(
            SPI_FREQUENCY,
            MSBFIRST,
            SPI_MODE0
        )
    );
}


// ============================================================
// SPI transaction END
// ============================================================

void Display::endTransaction()
{
    SPI.endTransaction();

    deselectAll();
}