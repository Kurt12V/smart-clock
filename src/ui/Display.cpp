#include "Display.h"
#include "Pins.h"
#include <Arduino.h>
#include <SPI.h>
#include <Adafruit_GFX.h>
#include <Adafruit_ST7789.h>


// ============================================================
// DISPLAY PINS
// ============================================================

static const int8_t TFT_CS[4] =
{
    PIN_TFT_CS1,
    PIN_TFT_CS2,
    PIN_TFT_CS3,
    PIN_TFT_CS4
};

static const int8_t TFT_RST[4] =
{
    PIN_TFT_RST1,
    PIN_TFT_RST2,
    PIN_TFT_RST3,
    PIN_TFT_RST4
};


// ============================================================
// ST7789 172x320
// ============================================================

ST7789_172x320::ST7789_172x320(
    int8_t cs,
    int8_t dc,
    int8_t rst,
    int8_t mosi,
    int8_t sclk
)
    : Adafruit_ST7789(
        cs,
        dc,
        mosi,
        sclk,
        rst
    )
{
}


// ============================================================
// DISPLAY INITIALIZATION
// ============================================================

void ST7789_172x320::begin172x320()
{
    // Инициализация физического дисплея
    init(
        172,
        320,
        SPI_MODE0
    );

    // Для конкретного ST7789 172x320
    // требуется смещение по X.
    setColRowStart(
        34,
        0
    );

    // Безопасная скорость SPI
    setSPISpeed(
        8000000
    );

    // Ориентация
    setRotation(
        0
    );

    // Инверсия цветов
    invertDisplay(
        true
    );
}


// ============================================================
// CONSTRUCTOR
// ============================================================

Display::Display()
    : _initialized(false)
{
    for (uint8_t i = 0; i < 4; i++)
    {
        _display[i] = nullptr;
    }
}


// ============================================================
// DESTRUCTOR
// ============================================================

Display::~Display()
{
    for (uint8_t i = 0; i < 4; i++)
    {
        if (_display[i] != nullptr)
        {
            delete _display[i];
            _display[i] = nullptr;
        }
    }
}


// ============================================================
// BEGIN
// ============================================================

bool Display::begin()
{
    if (_initialized)
    {
        return true;
    }


    // --------------------------------------------------------
    // BACKLIGHT
    // --------------------------------------------------------

    pinMode(
        PIN_TFT_BL,
        OUTPUT
    );

    digitalWrite(
        PIN_TFT_BL,
        HIGH
    );


    // --------------------------------------------------------
    // SPI
    // --------------------------------------------------------
    //
    // Все четыре дисплея используют одну SPI-шину.
    //
    // SCLK  -> общий
    // MOSI  -> общий
    // DC    -> общий
    //
    // CS    -> отдельный
    // RST   -> отдельный
    //
    // --------------------------------------------------------

    SPI.begin(
        PIN_TFT_SCLK,
        -1,
        PIN_TFT_MOSI,
        -1
    );


    // --------------------------------------------------------
    // INITIALIZE FOUR DISPLAYS
    // --------------------------------------------------------

    for (uint8_t i = 0; i < 4; i++)
    {
        // Создаем объект дисплея
        _display[i] =
            new ST7789_172x320(
                TFT_CS[i],
                PIN_TFT_DC,
                TFT_RST[i],
                PIN_TFT_MOSI,
                PIN_TFT_SCLK
            );


        // ----------------------------------------------------
        // CS
        // ----------------------------------------------------

        pinMode(
            TFT_CS[i],
            OUTPUT
        );

        digitalWrite(
            TFT_CS[i],
            HIGH
        );


        // ----------------------------------------------------
        // RST
        // ----------------------------------------------------

        pinMode(
            TFT_RST[i],
            OUTPUT
        );

        digitalWrite(
            TFT_RST[i],
            HIGH
        );


        // ----------------------------------------------------
        // INITIALIZE ST7789
        // ----------------------------------------------------

        _display[i]->begin172x320();


        // ----------------------------------------------------
        // CLEAR DISPLAY
        // ----------------------------------------------------

        _display[i]->fillScreen(
            ST77XX_BLACK
        );
    }


    // --------------------------------------------------------
    // FINISHED
    // --------------------------------------------------------

    _initialized = true;

    return true;
}


// ============================================================
// GET DISPLAY
// ============================================================

ST7789_172x320& Display::get(
    uint8_t index
)
{
    if (index >= 4)
    {
        index = 0;
    }

    return *_display[index];
}


// ============================================================
// BACKLIGHT
// ============================================================

void Display::setBacklight(
    bool state
)
{
    digitalWrite(
        PIN_TFT_BL,
        state ? HIGH : LOW
    );
}

