#pragma once

#include <Arduino.h>
#include <Preferences.h>

#include "Config.h"

// ============================================================
// PARAM
// ============================================================

enum class Param : uint8_t
{
    // --------------------------------------------------------
    // DISPLAY
    // --------------------------------------------------------

    BRIGHTNESS = 0,

    // --------------------------------------------------------
    // MATRIX
    // --------------------------------------------------------

    MATRIX_ENABLED,
    MATRIX_BRIGHTNESS,

    // --------------------------------------------------------
    // COB
    // --------------------------------------------------------

    COB_ENABLED,
    COB_BRIGHTNESS_1,
    COB_BRIGHTNESS_2,
    COB_BRIGHTNESS_3,
    COB_BRIGHTNESS_4,

    // --------------------------------------------------------
    // AUDIO
    // --------------------------------------------------------

    VOLUME_MEDIA,
    VOLUME_ALARM,
    VOLUME_SYSTEM,

    // --------------------------------------------------------
    // MICROPHONE
    // --------------------------------------------------------

    MIC_ENABLED,

    // --------------------------------------------------------
    // CLOCK
    // --------------------------------------------------------

    UTC_OFFSET,

    // --------------------------------------------------------
    // COB EFFECT
    // --------------------------------------------------------

    COB_EFFECT,

    // --------------------------------------------------------
    // COB SPEED
    // --------------------------------------------------------

    COB_SPEED,

    // --------------------------------------------------------
    // COUNT
    // --------------------------------------------------------

    COUNT
};


// ============================================================
// SETTINGS MANAGER
// ============================================================
//
// RAM → dirty → 700 ms → Preferences
//
// set() НИКОГДА не пишет во Flash напрямую.
//
// Это позволяет безопасно использовать SettingsManager
// из WebServer / Bluetooth / UI.
//
// ============================================================

class SettingsManager
{
public:

    // ========================================================
    // CONSTRUCTOR
    // ========================================================

    SettingsManager();


    // ========================================================
    // INIT
    // ========================================================

    bool begin();


    // ========================================================
    // UPDATE
    // ========================================================
    //
    // Вызывать регулярно из loop().
    //
    // Проверяет:
    // - есть ли изменения
    // - прошло ли SAVE_DELAY_MS
    //
    // ========================================================

    void update();


    // ========================================================
    // GET
    // ========================================================

    int get(
        Param p
    ) const;


    // ========================================================
    // SET
    // ========================================================
    //
    // Изменяет только RAM.
    //
    // Значение автоматически ограничивается диапазоном
    // конкретного параметра.
    //
    // Возвращает true только если значение действительно
    // изменилось.
    //
    // ========================================================

    bool set(
        Param p,
        int value
    );


    // ========================================================
    // LOAD ONE
    // ========================================================

    bool load(
        Param p
    );


    // ========================================================
    // LOAD ALL
    // ========================================================

    bool loadAll();


    // ========================================================
    // SAVE ONE
    // ========================================================

    bool save(
        Param p
    );


    // ========================================================
    // SAVE ALL
    // ========================================================

    bool saveAll();


    // ========================================================
    // RESET
    // ========================================================

    void resetAll();


    // ========================================================
    // DIRTY
    // ========================================================

    bool isDirty(
        Param p
    ) const;


    bool hasDirty() const;


    // ========================================================
    // FLUSH
    // ========================================================
    //
    // Немедленно сохраняет все изменения.
    //
    // ========================================================

    bool flush();


    // ========================================================
    // PARAM NAME
    // ========================================================

    static const char* paramName(
        Param p
    );


    // ========================================================
    // PARAM FROM NAME
    // ========================================================

    static bool paramFromName(
        const char* name,
        Param& out
    );


    // ========================================================
    // SAVE DELAY
    // ========================================================

    static constexpr uint32_t SAVE_DELAY_MS = 700;


private:

    // ========================================================
    // DEFAULTS
    // ========================================================

    void applyDefaults();


    // ========================================================
    // DIRTY
    // ========================================================

    void markDirty(
        Param p
    );


    void clearDirty(
        Param p
    );


    // ========================================================
    // INTERNAL SAVE
    // ========================================================

    bool saveDirty();


private:

    // ========================================================
    // VALUES
    // ========================================================

    int _values[
        static_cast<size_t>(Param::COUNT)
    ];


    // ========================================================
    // DIRTY MASK
    // ========================================================

    uint32_t _dirtyMask;


    // ========================================================
    // LAST CHANGE
    // ========================================================

    uint32_t _lastChangeMs;


    // ========================================================
    // STATE
    // ========================================================

    bool _initialized;


    // ========================================================
    // PREFERENCES
    // ========================================================

    Preferences _preferences;
};