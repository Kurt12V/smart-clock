#include "App.h"

#include "./Config.h"
#include "./Pins.h"
#include "./Constants.h"
#include "./Version.h"


// ============================================================
// CONSTRUCTOR
// ============================================================

App::App()
    : _settings(),

      _spiManager(),

      _i2sManager(),

      _sdManager(),

      _soundManager(
          _sdManager,
          _settings,
          _i2sManager
      ),

      _sensorManager(),

      _clockSystem(
          _settings
      ),

      _lighting(
          _settings
      ),

      _displaySystem(
          _settings,
          _clockSystem,
          _sensorManager,
          _spiManager
      ),

      _wifiManager(),

      _alarmManager(
          _sdManager,
          _clockSystem
      ),

      _alarmController(
          _alarmManager
      ),

      // --------------------------------------------------------
      // WEB MODULES
      // --------------------------------------------------------

      _webPageManager(),

      _webSettingsManager(
          _settings
      ),

      _webSDManager(
          _sdManager
      ),

      _webAudioManager(
          _soundManager,
          _sdManager
      ),

      _webAlarmManager(
          _alarmManager,
          _alarmController
      ),

      _webWiFiManager(
          _wifiManager
      ),

      _webServer(),

      _initialized(false)
{
}


// ============================================================
// BEGIN
// ============================================================

bool App::begin()
{
    // --------------------------------------------------------
    // SETTINGS
    // --------------------------------------------------------

    if (!initSettings())
        return false;


    // --------------------------------------------------------
    // SPI
    // --------------------------------------------------------

    if (!initSPI())
        return false;


    // --------------------------------------------------------
    // I2S
    // --------------------------------------------------------

    if (!initI2S())
        return false;


    // --------------------------------------------------------
    // SD
    // --------------------------------------------------------

    if (!initSD())
        return false;


    // --------------------------------------------------------
    // SOUND
    // --------------------------------------------------------

    if (!initSound())
        return false;


    // --------------------------------------------------------
    // CLOCK
    // --------------------------------------------------------

    if (!initClock())
        return false;


    // --------------------------------------------------------
    // SENSORS
    // --------------------------------------------------------

    if (!initSensors())
        return false;


    // --------------------------------------------------------
    // LIGHTING
    // --------------------------------------------------------

    if (!initLighting())
        return false;


    // --------------------------------------------------------
    // DISPLAY
    // --------------------------------------------------------

    if (!initDisplay())
        return false;


    // --------------------------------------------------------
    // ALARM
    // --------------------------------------------------------

    if (!initAlarm())
        return false;


    // --------------------------------------------------------
    // WIFI
    // --------------------------------------------------------

    if (!initWiFi())
        return false;


    // --------------------------------------------------------
    // WEB SERVER
    // --------------------------------------------------------

    if (!initWebServer())
        return false;


    // --------------------------------------------------------
    // READY
    // --------------------------------------------------------

    _initialized = true;

    return true;
}


// ============================================================
// UPDATE
// ============================================================

void App::update()
{
    if (!_initialized)
        return;


    // --------------------------------------------------------
    // SETTINGS
    // --------------------------------------------------------

    _settings.update();


    // --------------------------------------------------------
    // WIFI
    // --------------------------------------------------------

    _wifiManager.update();


    // --------------------------------------------------------
    // CLOCK
    // --------------------------------------------------------

    _clockSystem.update();


    // --------------------------------------------------------
    // SENSORS
    // --------------------------------------------------------

    _sensorManager.update();


    // --------------------------------------------------------
    // LIGHTING
    // --------------------------------------------------------

    _lighting.update();


    // --------------------------------------------------------
    // DISPLAY
    // --------------------------------------------------------

    _displaySystem.update();


    // --------------------------------------------------------
    // SOUND
    // --------------------------------------------------------

    _soundManager.update();


    // --------------------------------------------------------
    // ALARM
    // --------------------------------------------------------

    _alarmManager.update();

    _alarmController.update();


    // --------------------------------------------------------
    // WEB
    // --------------------------------------------------------

    _webServer.update();
}


// ============================================================
// SETTINGS
// ============================================================

bool App::initSettings()
{
    return _settings.begin();
}


// ============================================================
// SPI
// ============================================================

bool App::initSPI()
{
    return _spiManager.begin();
}


// ============================================================
// I2S
// ============================================================

bool App::initI2S()
{
    return _i2sManager.begin();
}


// ============================================================
// SD
// ============================================================

bool App::initSD()
{
    return _sdManager.begin(
        PIN_SD_CS
    );
}


// ============================================================
// SOUND
// ============================================================

bool App::initSound()
{
    return _soundManager.begin();
}


// ============================================================
// CLOCK
// ============================================================

bool App::initClock()
{
    return _clockSystem.begin();
}


// ============================================================
// SENSORS
// ============================================================

bool App::initSensors()
{
    return _sensorManager.begin();
}


// ============================================================
// LIGHTING
// ============================================================

bool App::initLighting()
{
    return _lighting.begin();
}


// ============================================================
// DISPLAY
// ============================================================

bool App::initDisplay()
{
    return _displaySystem.begin();
}


// ============================================================
// ALARM
// ============================================================

bool App::initAlarm()
{
    if (!_alarmManager.begin())
        return false;


    _alarmController.begin();

    return true;
}


// ============================================================
// WIFI
// ============================================================

bool App::initWiFi()
{
    return _wifiManager.begin();
}


// ============================================================
// WEB SERVER
// ============================================================

bool App::initWebServer()
{
    // --------------------------------------------------------
    // Register web modules
    // --------------------------------------------------------

    _webServer.setPageManager(
        _webPageManager
    );


    _webServer.setSettingsManager(
        _webSettingsManager
    );


    _webServer.setSDManager(
        _webSDManager
    );


    _webServer.setAudioManager(
        _webAudioManager
    );


    _webServer.setAlarmManager(
        _webAlarmManager
    );


    _webServer.setWiFiManager(
        _webWiFiManager
    );


    // --------------------------------------------------------
    // Start server
    // --------------------------------------------------------

    return _webServer.begin(
        _settings
    );
}